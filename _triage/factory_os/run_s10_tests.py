def check(label, ok, detail=''):
    if ok:
        sys.stdout.write('  [OK ] %s\n' % label)
    else:
        FAILS.append(label)
        sys.stdout.write('  [FAIL] %s\n' % label)
        if detail:
            sys.stdout.write('        -> %s\n' % detail)
    return ok


def refuses(label, problems, expect_id):
    """A refusal must be refused FOR THE STATED REASON. `problems` being non-empty is satisfied by
    the shape check on every one of these inputs, so matching on emptiness would let a case pass
    on an unrelated defect and then stop noticing the one it was written for."""
    NAMED.add(expect_id)
    hit = [p for p in problems if p.startswith(expect_id + ' ')]
    return check('%-3s %s' % (expect_id, label), bool(hit),
                 'expected a %s finding, got %s' % (expect_id, problems or 'nothing'))


def accepts(label, problems):
    """THE SPECIFICITY HALF. Every refusal below needs a control that must NOT fire, or the suite
    would pass just as well against a validator that refuses everything
    (memory `gate-specificity-not-just-sensitivity`)."""
    return check('CTL %s' % label, not problems, 'expected no finding, got %s' % problems)


