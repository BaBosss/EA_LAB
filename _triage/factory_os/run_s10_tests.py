    # 🔴 /scrutinize round 2 proved BY PROBE that `10000` and `10000.0` produced two ExecutionKey
    # digests for one deposit. design 4.5 names the identical failure for candidate_digest. The
    # payload nests, so the flat pass that fixed the key is not enough here -- and this is the
    # case that says so.
    a = copy.deepcopy(PAYLOAD)
    a['parameters'] = {'deposit': 10000, '_02_SlAtrMult': 1.5}
    b = copy.deepcopy(PAYLOAD)
    b['parameters'] = {'deposit': 10000.0, '_02_SlAtrMult': 1.5}
    check('the same deposit spelled two ways gives ONE digest, NESTED inside parameters',
          C.candidate_digest(a) == C.candidate_digest(b),
          '%s vs %s' % (C.candidate_digest(a)[:12], C.candidate_digest(b)[:12]))
    a = copy.deepcopy(PAYLOAD)
    a['evidence'][0]['pf'] = 2
    b = copy.deepcopy(PAYLOAD)
    b['evidence'][0]['pf'] = 2.0
    check('the same PF spelled two ways gives ONE digest, nested inside a LIST of objects',
          C.candidate_digest(a) == C.candidate_digest(b))

    # A bool is an int in Python. Normalizing it into one would make `True` and `1` the same
    # parameter, which is a different candidate on a broker where it is a mode switch.
    a = copy.deepcopy(PAYLOAD)
    a['parameters'] = {'AllowLive': True}
    b = copy.deepcopy(PAYLOAD)
    b['parameters'] = {'AllowLive': 1}
    check('True and 1 stay DIFFERENT (bool is a subclass of int, and collapsing them would '
          'silently merge two configurations)', C.candidate_digest(a) != C.candidate_digest(b))

    # THE DEPENDENCY IS MEASURED, not declared. If someone gave this module its own serializer,
    # replacing scheduler's would stop moving the candidate digest -- and that is what is checked.
    real = S.canonical
    try:
        S.canonical = lambda obj: json.dumps(obj, sort_keys=True, separators=(', ', ': '))
        with_swapped = C.candidate_digest(PAYLOAD)
    finally:
        S.canonical = real
    check('candidate_digest really goes THROUGH scheduler.canonical -- swap the serializer and '
          'the digest moves', with_swapped != C.candidate_digest(PAYLOAD),
          'the digest did not move, so this module is not using the shared serializer and the '
          '"one canonical form" claim is a comment')

    # ...and the same probe for the normalization, which is the half the round-2 defect lived in.
    int_pf = copy.deepcopy(PAYLOAD)
    int_pf['evidence'][0]['pf'] = 2
    float_pf = copy.deepcopy(PAYLOAD)
    float_pf['evidence'][0]['pf'] = 2.0
    real_norm = S.normalize_numbers
    try:
        S.normalize_numbers = lambda obj: obj
        split = C.candidate_digest(int_pf) != C.candidate_digest(float_pf)
    finally:
        S.normalize_numbers = real_norm
    check('...and really goes through normalize_numbers -- remove it and 2 vs 2.0 splits again '
          '(the /scrutinize round 2 defect, reproduced on demand)', split,
          'the pair stayed equal with the normalization removed, so this probe proves nothing '
          'about the normalization')

    # The flat form the key uses and the recursive form the payload uses must agree over the key,
    # measured on the real field list rather than argued for in a comment.
    key = dict((f, 'x') for f in S.EXECUTION_KEY_FIELDS)
    key.update({'deposit': 10000.0, 'model': 1, 'leverage': 100})
    flat = dict((f, int(v) if isinstance(v, float) and v.is_integer() else v)
                for f, v in key.items())
    check('the recursive normalization agrees with the flat one over a real ExecutionKey',
          S.canonical(S.normalize_numbers(key)) == S.canonical(flat))


