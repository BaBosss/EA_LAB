def part2_attestation():
    sys.stdout.write('\nPART 2 -- attestation: %d (event_type x actor) cells, each decided\n'
                     % len(EXPECTED))
    decided = 0
    for (etype, actor) in sorted(EXPECTED):
        want = EXPECTED[(etype, actor)]
        kw = {} if etype == 'OBSERVED' else {'authorization_ref': copy.deepcopy(AUTH)}
        ev = _event(etype, actor, **kw)
        problems = A.validate_event(ev, [])
        if want is None:
            ok = accepts('%-20s by %-10s is allowed' % (etype, actor), problems)
        else:
            ok = refuses('%-20s by %-10s' % (etype, actor), problems, want)
        if ok:
            decided += 1
